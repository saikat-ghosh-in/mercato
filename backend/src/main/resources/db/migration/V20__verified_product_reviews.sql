CREATE TABLE product_review (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id varchar(30) NOT NULL,
    buyer_id varchar(100) NOT NULL,
    order_line_id bigint NOT NULL REFERENCES order_lines_snapshot(id),
    rating integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
    review_text varchar(2000) NOT NULL,
    video_url varchar(255),
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT uk_product_review_buyer UNIQUE (product_id, buyer_id)
);

CREATE INDEX idx_product_review_recent ON product_review (product_id, created_at DESC, id DESC);
CREATE INDEX idx_product_review_buyer ON product_review (buyer_id, product_id);

CREATE TABLE product_review_photo (
    review_id bigint NOT NULL REFERENCES product_review(id) ON DELETE CASCADE,
    position integer NOT NULL CHECK (position BETWEEN 0 AND 2),
    photo_url varchar(255) NOT NULL,
    PRIMARY KEY (review_id, position)
);
